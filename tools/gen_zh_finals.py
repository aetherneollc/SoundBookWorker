#!/usr/bin/env python3
"""Regenerate renderer/zh_finals.py, the hanzi -> mouth-shape table used by voice_cues.

Needs pypinyin (``pip install pypinyin``); the renderer itself does not.

    python tools/gen_zh_finals.py
"""
from __future__ import annotations

import textwrap
from pathlib import Path

from pypinyin import Style, pinyin

OUTPUT = Path(__file__).resolve().parents[1] / 'renderer' / 'zh_finals.py'
# Finals in pypinyin's strict spelling (iou = iu, uei = ui, uen = un, v = ü).
OPEN = {'a', 'ia', 'ua', 'ai', 'uai', 'ao', 'iao', 'an', 'uan', 'ang', 'iang', 'uang'}
ROUND = {'o', 'uo', 'ou', 'iou', 'ong', 'iong', 'u', 'v', 'vn', 'io'}
# Interjections that scripts use and GB2312 does not all carry.
EXTRA = '嗯呣噷哼啥咋嘛噢哎唉呃诶嘿喂哦呗咯啰嘞呐哟唷嗨哇呀啦吧吗呢啊哈嘻嗬咦哩喽噻嗒咔嚓啪砰轰咚嘀'
HEADER = '''"""Mouth-shape tendency of common Chinese characters.

Each hanzi is filed under the main vowel of its most common reading:

* ``OPEN_FINALS``  : a, ia, ua, ai, uai, ao, iao, an, uan, ang, iang, uang
* ``ROUND_FINALS`` : o, uo, ou, iu, ong, iong, u, ü, ün
* ``NARROW_FINALS``: i, in, ing, e, ei, en, eng, er, ie, ian, üan, üe, ui, un, and
  the syllabic nasals

The characters are GB2312 levels 1 and 2 plus a few interjections. This file is
generated by ``tools/gen_zh_finals.py`` with pypinyin; pypinyin is not needed at run
time. ``voice_cues`` only uses the table as a hint, so a polyphonic character filed
under its commoner reading costs nothing worse than a slightly different mouth.
"""
'''


def gb2312_hanzi() -> list[str]:
    chars = []
    for high in range(0xB0, 0xF8):
        for low in range(0xA1, 0xFF):
            try:
                chars.append(bytes([high, low]).decode('gb2312'))
            except UnicodeDecodeError:
                pass
    return chars


def block(name: str, chars: list[str]) -> str:
    lines = '\n'.join(f"    '{line}'" for line in textwrap.wrap(''.join(chars), 64))
    return f'{name} = (\n{lines}\n)\n'


def main() -> None:
    chars = gb2312_hanzi()
    chars += [char for char in dict.fromkeys(EXTRA) if char not in set(chars)]
    groups: dict[str, list[str]] = {'a': [], 'o': [], 'i': []}
    for char in chars:
        final = pinyin(char, style=Style.FINALS, strict=True, heteronym=False)[0][0].replace('ü', 'v')
        if final == char:
            continue  # pypinyin has no reading for it.
        groups['a' if final in OPEN else 'o' if final in ROUND else 'i'].append(char)
    source = '\n'.join((
        HEADER,
        block('OPEN_FINALS', groups['a']),
        block('ROUND_FINALS', groups['o']),
        block('NARROW_FINALS', groups['i']),
    ))
    OUTPUT.write_text(source, encoding='utf-8', newline='\n')
    print(f'{OUTPUT}: ' + ', '.join(f'{name} {len(found)}' for name, found in groups.items()))


if __name__ == '__main__':
    main()
